// Build an explicit source slice; never rewrite JSX, classes or function bodies.
import ts from 'typescript';
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
export function extractDeclarations(source,names){
 const file=ts.createSourceFile('upstream.tsx',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
 if(file.parseDiagnostics.length)throw Error('Official TSX no longer parses');
 return names.map(name=>{
  const found=file.statements.filter(node=>
   (ts.isFunctionDeclaration(node)&&node.name?.text===name)||
   (ts.isVariableStatement(node)&&node.declarationList.declarations.length===1&&node.declarationList.declarations[0].name.getText(file)===name));
  if(found.length!==1)throw Error(`Official declaration boundary changed: ${name}`);
  return found[0].getText(file);
 });
}
