"""Import the owner's named PNG archive without resampling or altering its art.

Usage: python3 scripts/official-web/import-pokemon-avatars.py /path/to/archive.zip
The manifest preserves original names/hashes; stable IDs distinguish all forms.
"""
import hashlib
import json
import re
import struct
import sys
from pathlib import Path
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[2]
PUBLIC = ROOT / "frontends/raft/packages/web/public/avatars/pokemon"
MANIFEST = ROOT / "frontends/raft/loom/avatars/pokemon.json"
KEYS = ROOT / "packages/protocol/src/pokemon-agent-avatar-keys.ts"
FORMS = {
    "！": "exclamation", "？": "question", "普通形态": "normal",
    "晴天形态": "sunny", "雨天形态": "rainy", "雪天形态": "snowy",
    "攻击形态": "attack", "速度形态": "speed", "防御形态": "defense",
}
GROUPS = [
    {"id": "kanto", "name": "关都 · 001–151", "through": 151},
    {"id": "johto", "name": "城都 · 152–251", "through": 251},
    {"id": "hoenn", "name": "丰缘 · 252–386", "through": 386},
    {"id": "sinnoh", "name": "神奥 · 387–493", "through": 493},
    {"id": "unova", "name": "合众 · 494–506", "through": 506},
]


def main(archive):
    avatars, assets = [], {}
    with ZipFile(archive) as z:
        for entry in z.infolist():
            match = re.fullmatch(r"小精灵头像/(\d{3}) ([^/]+)\.png", entry.filename)
            if not match:
                raise ValueError(f"Unexpected archive entry: {entry.filename}")
            number, name = match.groups()
            form = name.partition("-")[2]
            suffix = FORMS.get(form, form.lower())
            key = f"pokemon-{number}" + (f"-{suffix}" if form else "")
            if not re.fullmatch(r"pokemon-[a-z0-9-]+", key) or key in assets:
                raise ValueError(f"Invalid/duplicate identity: {key}")
            data = z.read(entry)
            if data[:8] != b"\x89PNG\r\n\x1a\n" or struct.unpack(">II", data[16:24]) != (512, 512):
                raise ValueError(f"Unexpected image format: {entry.filename}")
            digest = hashlib.sha256(data).hexdigest()
            filename = f"{key}-{digest[:16]}.png"
            group = next(g["id"] for g in GROUPS if int(number) <= g["through"])
            avatars.append({
                "id": key, "name": name, "number": int(number), "group": group,
                "url": f"/avatars/pokemon/{filename}", "sourcePath": entry.filename,
                "sha256": digest, "bytes": len(data), "width": 512, "height": 512,
            })
            assets[key] = (filename, data)
    if len(avatars) != 539:
        raise ValueError(f"Expected 539 images, got {len(avatars)}")
    PUBLIC.mkdir(parents=True, exist_ok=True)
    wanted = {filename for filename, _ in assets.values()}
    for old in PUBLIC.iterdir():
        if old.name not in wanted:
            old.unlink()
    for filename, data in assets.values():
        (PUBLIC / filename).write_bytes(data)
    manifest = {
        "source": {
            "archive": archive.name,
            "archiveSha256": hashlib.sha256(archive.read_bytes()).hexdigest(),
            "suppliedBy": "Owner, 2026-10-30", "transformation": "none; original PNG bytes",
        },
        "groups": [{"id": g["id"], "name": g["name"]} for g in GROUPS],
        "avatars": avatars,
    }
    MANIFEST.with_name("pokemon.provenance.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    MANIFEST.write_text(json.dumps({
        "groups": manifest["groups"],
        "avatars": [{k: a[k] for k in ("id", "name", "group", "url")} for a in avatars],
    }, ensure_ascii=False, indent=2) + "\n")
    KEYS.write_text(
        "// GENERATED by scripts/official-web/import-pokemon-avatars.py; identities only.\n"
        "export const POKEMON_AGENT_AVATAR_KEYS: readonly string[] = [\n"
        + "".join(f'  "{a["id"]}",\n' for a in avatars) + "];\n"
    )
    print(f"Imported {len(avatars)} original PNGs ({sum(a['bytes'] for a in avatars)} bytes)")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
